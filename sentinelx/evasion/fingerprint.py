_COMPILED = []
for _sig in WAF_SIGNATURES:
    _COMPILED.append({
        "name": _sig["name"],
        "headers": [(re.compile(k, re.I), re.compile(v, re.I))
                    for k, v in _sig["headers"].items()],
        "cookies": [re.compile(c, re.I) for c in _sig["cookies"]],
        "body": [re.compile(b, re.I) for b in _sig["body"]],
        "status": set(_sig.get("status", [])),
    })


def _match_response(sig: dict, headers: dict, cookies: list[str],
                    body: str, status: int) -> bool:
    for name_rx, val_rx in sig["headers"]:
        for hname, hval in headers.items():
            if name_rx.search(hname) and val_rx.search(hval or ""):
                return True
    for crx in sig["cookies"]:
        if any(crx.search(c) for c in cookies):
            return True
    for brx in sig["body"]:
        if brx.search(body):
            return True
    if sig["status"] and status in sig["status"] and body.strip():
        # block status alone is weak; require at least a hint of blocking
        if re.search(r"block|denied|forbidden|not acceptable|incident",
                     body, re.I):
            return True
    return False


async def fingerprint(client: ScanClient, url: str) -> list[str]:
    """Probe a URL normally and with a malicious query string, then match
    response headers/cookies/body against 25 WAF signatures.

    Returns a sorted list of matched WAF/proxy product names."""
    matched: set[str] = set()
    probes = [
        url,
        url + ("&" if "?" in url else "?")
        + "sxprobe=" + _quote("<script>alert('sx')</script>", safe=""),
    ]
    for probe in probes:
        resp = await client.get(probe)
        if not resp:
            continue
        headers = {k: v for k, v in resp.headers.items()}
        cookies = [v.decode("latin1") if isinstance(v, bytes) else v
                   for k, v in resp.headers.raw if k.lower() == b"set-cookie"]
        body = resp.text[:100_000]
        for sig in _COMPILED:
            if _match_response(sig, headers, cookies, body, resp.status_code):
                matched.add(sig["name"])
    return sorted(matched)
